        <h4>PhilHealth Revokes Accreditation of Bonifacio Medical Clinic in CDO<span> 
          April 12, 2012</span></h4>
        <div> 
          <ul class="gallery clearfix">
            <li><a href="../2012/images/revokes_accreditation.jpg" rel="prettyPhoto[gallery2]" title=""><img src="../2012/images/revokes_accreditation.jpg" width="80" height="54" alt="PhilHealth Revokes Accreditation of Bonifacio Medical Clinic in CDO" /></a></li>
            <li><a href="../2012/images/revokes_accreditation2.jpg" rel="prettyPhoto[gallery2]" title=""><img src="../2012/images/revokes_accreditation2.jpg" alt="PhilHealth Revokes Accreditation of Bonifacio Medical Clinic in CDO" width="80" height="54" border="0" /></a></li>
          </ul>
        </div>
                <p>CAGAYAN DE ORO CITY – The PhilHealth Regional Office 10 has revoked the accreditation of a medical clinic in Misamis Occidental for fraudulently filing claims for non-admitted patients and other misrepresentations.</p>
                <p>PhilHealth Regional Vice President for Northern Mindanao Datu Masiding M. Alonto Jr. said Bonifacio Medical Clinic located at Purok 4, Poblacion, Bonifacio town was found guilty for misrepresentation by furnishing false and incorrect information and can no longer process claim reimbursements of PhilHealth members effective March 16, 2012.</p>
                <p>Alonto said the order came after a thorough investigation conducted by PhilHealth Regional Office 10 – Legal Office and that the revocation of BMC's accreditation is permanent effective March 16, 2012.</p>
                <p>PhilHealth has already filed a number of cases against the clinic  for various irregularities since the approval of its accreditation in 1998. Twenty-nine (29) of these were later found to be fraudulent claims for "non-admitted” patients.</p>
                <p>The cases were filed after PhilHealth 10 – Legal Office  found irregularities on the legitimacy of the patient's confinement, since a trend of family confinement and mandatory admission of three days were detected, Alonto said.</p>
                <p>Alonto said these acts are tantamount to grave breach of the warranties of accreditation, which is  punishable by revocation of the clinic's status as an accredited PhilHealth provider.</p>
                <p>In its decision dated November 14, 2011, the Arbitration Office found BMC violating Section 141 or Claims for Non-admitted Patients of Rule XXVIII of the Implementing Rules and Regulations of the  National Health Insurance Act of R.A. 7875 as amended by R.A. 9241.</p>
                <p><em>"BMC undermines the goal of PhilHealth to provide secured hospitalization for its members,"</em> Alonto added.</p>
                <p>As of this writing, Atty. Allan G. Panolong, Head of the Legal Office of PhilHealth 10 received decisions for BMC for 12 counts of revocation, six orders of suspension and aggregate fine of P710,000.00.</p>
                <p>Meanwhile, Alonto advised members to instead avail themselves of their PhilHealth benefits in other accredited facilities in the city. (END)</p>
                
                
