		<p>The Philippine Health Insurance Corporation (PhilHealth) is now adopting state-of-the-art technology to bring its existing measures to detect and prevent health insurance fraud to the next level.</p>
<p>The agency is currently working on a 'proof of concept' together with technology providers for 'liveness check' and 'identity authentication' solutions that will be rolled out in all its offices and participating health facilities in the year 2020.</p>
<p><em>"Liveness check will help us validate if the member or a dependent is still alive or has expired during confinement, while identity authentication should help us verify if they are who they claim to be,"</em> explained PhilHealth President and Chief Executive Officer Ricardo C. Morales during a recent simulation exercise with participating technology provider Galeleo and Element Artificial Intelligence Groups. <em>"These technologies help ensure that only those claims of living members or patients are paid by PhilHealth,"</em> he added.</p>
<p>PhilHealth saw the need to institute biometric checks at the level of health facilities to ensure the integrity of hospital claims. The biometric check will include fingerprint scanning and facial recognition to capture different facial structures and landmarks such as eyes and facial contours to ensure the integrity of claims. END</p>
	
