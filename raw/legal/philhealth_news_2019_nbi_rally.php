		<p>The anti-fraud campaign launched by Dr. Roy Ferrer, acting president of the Philippine Health Insurance Corporation (PhilHealth) is gaining momentum bolstered by the expressed support of investigative agencies, enforcers, professional groups and hospital associations.</p>
		<p>The National Bureau of Investigation (NBI), Philippine Medical Association (PMA), Philippine Hospital Association (PHA), and the Professional Regulation Commission (PRC) have thrown their support for PhilHealth's campaign against malpractices and violations that are defrauding government of its funds and resources. </p>
		<p>The growing base of support for PhilHealth is prompted by people's perception that the Acting PhilHealth President has <em>"shown his grit and determination to stamp out health insurance fraud,"</em> said one physician who belongs to the PMA. This is specially true, he noted, <em>"since PhilHealth has succeeded in identifying violators, prosecuting them and are meted penalties."</em></p>
		<p>The NBI has made its investigative skills and facilities available to PhilHealth to catch wrongdoers, produce evidence of fraud, and assist prosecutors to buttress their cases against violators.</p>
		<p>The PMA, the countrywide association of medical doctors, has pledged its support for PhilHealth, vowing to apply peer pressure against practitioners <em>"who take the low road of deception and crime."</em> <em>"Ours is an intelligence network than can easily spot our fellow practitioners if they make false medical claims, fabricate forms and documents, and submit multiple claims for one disease"</em>, a PMA official said.</p>         
        
		<p><em>"We are ashamed of hospitals which betray the trust of PhilHealth when they engage in fraudulent acts,"</em> said an official of PHA, who added that their association will not hesitate taking out these unethical hospitals from their membership roll. There have been cases of hospitals which connived with doctors to submit false claims – just so to make money.</p>
		<p>The PRC, the regulator and licensing body for all professionals, said it is ready to suspend the licenses of unscrupulous medical doctors and participating nurses if evidence would show that they engaged in fraudulent activities, said a PRC official. <em>"It is always good to cleanse our professional ranks of unethical and abusive peers,"</em> he added.</p>
		<p>Dr. Ferrer, visibly elated by this pervasive show of support, declared that PhilHealth will be able to put an end to this health insurance fraud "faster than expected" due to the support of public and private agencies. <em>"I am vindicated and reassured that our courageous effort to frontally face the problem has drawn support from well-meaning public and private groups,"</em> he beamed.</p>
		<p>The broadening support for PhilHealth has augured well for the early success of the anti-fraud campaign, and has reassured the hundred million PhilHealth members that the collective PhilHealth Fund will remain solid and robust. It will be recalled that PhilHealth ended 2018 with 11.6 billion in net income.</p>
		<p>PhilHealth's financial health is further bolstered by the Universal Health Care  (UHC) Law which would raise premium contributions from PhilHealth members, national government subsidies, and shares from such government agencies like th Philippine Amusement Gaming Corporation (Pagcor) and the Philippine Charity Sweepstakes (PCSO).</p>
        
		<p>With these developments, Dr. Ferrer has rallied his PhilHealth "army" to be "very vigilant and aggressive" in bringing this anti-fraud campaign to a suitable conclusion: <em>"Make fraud a thing of the past, and enable PhilHealth to focus on its mandate to help patients in confinement and in disease treatment."</em>(END)</p>
        


