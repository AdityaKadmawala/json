		<p>The Philippine Health Insurance Corporation (PhilHealth) has thrown its support for Senate President Vicente Sotto who vowed to run after culprits who are defrauding government of millions of funds due to fraudulent practices, while the state health insurer took exception to the claims even of doctors who have chosen the "low road of graft and corruption."</p>
		<p>Responding to the issue raised by Senate President Sotto at a recent budget deliberation in the Senate identifying a certain neurologist from South Cotabato who is allegedly perpetrating practices of fraud in order to earn millions, PhilHealth fully supports the Senate President in putting a stop to fraudulent practices that are costing the government hundreds of millions of PhilHealth funds.</p>
        <p>In reference to several recent reports, the doctor, Dr. Dennis Menguita, is allegedly perpetrating practices of fraud of deception in order to earn millions. According to information, this doctor allegedly conducts a <em>modus operandi</em> where he "recruits patients" purportedly to be confined in certain favored hospitals, those the neurologist is affiliated with. Then, the doctor conspire to make fraudulent claims based on fake confinements and other medical services.</p>
        <p>Further investigation disclosed that the said neurologist has been allegedly "in cahoots" with three hospitals in South Cotabato. Senate Chief Sotto identified them as St. Louis Medical CL and Hospital, Allah Valley Medical Specialist Hospital Inc., and Arturo Pinggoy Medical Center. The hospitals are also under investigation.</p>
        <p><em>"We are grateful that we have no less than the Senate President who vowed to help us protect the National Health Insurance Fund through a strong anti-fraud campaign across all internal and external spheres of PhilHealth,"</em> Vice President Shirley Domingo, Official Spokesperson of PhilHealth said.  </p>
        <p><em>"PhilHealth strongly condemns this act, as we warn the culprits that their days are numbered,"</em> declared the PhilHealth executive.</p>
        <p>PhilHealth has been relentless in its campaign against fraud committed by unscrupulous individuals and institutions. They brazenly bleed the health insurance fund intended for members' benefits, and thus they should not go unpunished.</p>
        <p>Over the years, the government health insurer has filed cases against some of its partner-stakeholders, suspending or penalizing erring health care providers nationwide.</p>
        <p>We assure our stakeholders and the general public that this matter has been the subject of non-stop investigation since last year when the fraudulent acts were first discovered.</p>
        <p><em>"We have found probable cause against the erring doctor,"</em> Dr. Domingo said, adding that PhilHealth had already filed at least 21 cases of misrepresentation and breach of warranties of accreditation/performance commitment against Dr. Menguita.</p>
        <p>PhilHealth has also charged other individuals found committing fraudulent acts – which include soliciting from patients, furnishing false and incorrect information, and falsification of public documents.</p>                                
        <p><em>"We will leave no stone unturned until all those who abuse the Program are punished with the full force of the law."</em></p>

        
        


