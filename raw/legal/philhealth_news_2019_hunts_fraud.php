		<p>The Philippine Health Insurance Corporation (PhilHealth) intensifies its campaign against fraud in light of the Universal Health Care law's enactment. <em>"We cannot afford to fall short on our efforts to halt the progression of these deceitful practices; especially now that the National Health Insurance Program (NHIP) needs a strong and stable fund to enforce the Universal Health Care Act,"</em> said Dr. Roy B. Ferrer, PhilHealth Acting President and CEO. <em>"We take it upon ourselves to initiate collaborations with relevant government agencies and private entities to uphold the moral standards by which our society must prosper,"</em> Ferrer added.</p>
		<p>These partnerships ascertain the success of anti-fraud activities in order to ensure reliable and consistent services for PhilHealth beneficiaries.</p>
		<p>The Corporation recently signed a Memorandum of Agreement with the National Bureau of Investigation and commenced a strengthened effort to suppress fraud. PhilHealth also joined hands with the Philippine Medical Association and Philippine Hospital Association to confront erring health care institutions; while the Professional Regulation Commission was tapped to dispense sanctions upon dishonest health professionals.</p>
		<p>Last year, PhilHealth filed about 5,000 cases with its Prosecution Department against health care institutions and professionals. The Corporation only took 17 days to process a case build-up that entails a thorough data-gathering method. Fraudulent transactions spanning from professionals recruiting members into a bogus "Free Wellness Program" only to be paid for by PhilHealth to hospitals and dialysis centers including filing claims for deceased patients were exposed. These cases were investigated and prosecuted accordingly. </p>    
		<p>Stiff penalties and fines were imposed upon those involved and measures were formulated to prevent future occurrence of fraud. These anti-fraud efforts relied on truthful evidence extracted with careful deliberation.</p>
		<p>As a testament to its stance against fraud, PhilHealth castigated 71 hospitals across the nation due to breach in accreditation, misconduct, and other grounds that warrant such punishment. Moreover, members of the so-called "mafia" within its ranks have been uncovered and suspended by PhilHealth due to a string of offenses against the Corporation. Investigations were conducted to ensure proper actions against the dishonest officials.</p>
		<p><em>"Despite our commitment to fight fraud, we do not flail our swords aimlessly and chop down an innocent arm,"</em> Ferrer cleared. <em>"Even if goals for anti-fraud efforts are set, devious practices are not tolerated just for the sake of reaching those goals. We are beyond that,"</em> he further clarified. The Corporation ensures its counter-fraud measures were guided by integrity, upheld by ethics, and administered with precision.</p>
		<p>Help fight fraud! Protect Your NHIP! Report fraud to PhilHealth's 24/7 Corporate Action Center Hotline, (02) 441-7442, e-mails may also be sent to actioncenter@philhealth.gov.ph. For more updates, members and stakeholders are encouraged to follow PhilHealth on Facebook (facebook.com/PhilHealthofficial) and Twitter (@teamphilhealth). END</p>        
      

        
        


