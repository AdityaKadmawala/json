		<p>PhilHealth asserted that its recent actions against erring hospitals are to ensure more stringent measures in its fight against providers who defraud the Corporation. The State health insurance agency however, assures the public that measures are being done so that member's availment of services shall not be compromised.</p> 
        <p>The assertion was in response to a paid advertisement from an individual who claims to head a group of private hospitals alleging that several of their members in Mindanao were not given the opportunity to be heard in formal hearings of the cases filed against them.</p>
        <p><em>"Our legal procedures follow strict rules on due process when cases are filed against our providers. These hospitals were properly asked to explain their side on their alleged involvements in fraudulent activities,"</em> PhilHealth President and CEO BGen. Ricardo C. Morales said, adding that they observed pertinent rules and procedures before arriving at these decisions. <em>"Proper communications were also given so they can properly notify their patients of their situation,"</em> Morales added.</p>
        <p>The PhilHealth Chief said that <em>"many of his alleged member-hospitals disown his insinuations. I advise that he choose his words carefully in order not to compromise those who are in good standing and are in good partnership with PhilHealth."</em> Morales advised hospitals to directly coordinate with PhilHealth's regional offices on any issues arising from their claims.</p>
        <p>Earlier last week, PhilHealth announced the withdrawal of accreditation privileges of Dr Arturo P. Pingoy Medical Center and Allah Valley Medical Specialist Center Inc., and the suspension of General Santos Doctors Hospital due to alleged involvement in fraudulent activities based on its policy of withdrawing accreditation if cases have been filed in its Arbitration Office. Morales vowed that PhilHealth shall not tolerate filing of fraudulent claims by its providers.</p>
        <p><em>"Much has been said of the criminal cases against WellMed that made headlines in June this year. We are not allowing this to happen again. We are now imposing more stringent if not uncompromising actions at the slightest sign of fraud,"</em> he stressed.</p>
        
        <h5>Member's welfare still a consideration</h5>
        <p>Notwithstanding the cases that are now on process with the agency, he announced that they have reached a modus vivendi, or an arrangement with the concerned hospitals so that members are not disenfranchised while there is continuing investigation on their suspicious claims.</p>
        <p>He added that they are now instituting reforms to be more responsive and proactive in the early detection of irregular practices not just of hospitals but also of members, employers and even their own officials and employees in order to protect the members' funds.</p>
        <p><em>"Do not get us wrong. Our providers are our partners in service but once trust and respect are violated by any of the parties then it is incumbent upon us to investigate and enforce the law. This is what our members are expecting of us, no more, no less"</em> stressed the Chief. END</p>



