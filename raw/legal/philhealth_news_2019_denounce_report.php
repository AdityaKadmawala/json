		<p><strong>Reacting to a series of articles that PhilHealth is plagued by fraud and corruption, PhilHealth  denounced in strongest terms the seemingly orchestrated efforts of people within and outside the Corporation to destroy the name of PhilHealth and undermine its efforts in fraud identification and control.</strong></p>
        
		<h5><strong>The truth behind the allegations</strong></h5>
		<p>There have been and there may be fraudulent activities at present that have been detected by the Corporation.  But to say that PhilHealth has not been taking action is an utter lie. The  Corporation has filed at least 13 criminal complaints against providers now pending in the Courts, approx. 200 cases against erring employers, 27 cases of unethical behavior of its provider doctors before the Professional Regulation Commission.  Charges before PhilHealth's Arbitration office against 81 facilities and 26 doctors and more than 271 facilities and 206 doctors are facing preliminary investigation.</p>
		<p>PhilHealth has revoked the accreditation of 21 facilities and 35 health care professional, suspended 147 facilities and professionals and imposed fines to more than 600 combined facilities and professionals.</p>
		<p>Moreover, since 2008, PhilHealth has denied 1,294 applications for the renewal of accreditation after due evaluation of capacity and integrity of the health care provider.  In addition, it has withdrawn accreditation of 71 providers.</p>
		
		<h5><strong>Ghost dialysis treatment</strong></h5>
        <p>With regards to dialysis treatments of dead patients in WellMed, 5 formal charges have been filed in PhilHealth's Arbitration Office involving 83 cases/counts against the institution and 41 counts against at least 2 involved doctors.</p>
		<p>The Corporation does not condone such acts as it undermines the people's entitlement, hence it has withdrawn the accreditation of WellMed Dialysis Center and Laboratory Corporation in view of the fraudulent claims for dialysis services filed on behalf of deceased patients. A total of 8000+ complaints against its health care providers nationwide are now also being investigated in its 17 Regional offices with the highest number in Region 12. </p>

		<h5><strong>Pamela del Rosario case</strong></h5>
		<p>It should be emphasized that the case which was recently made public involving Pamela del Rosario who connived with a former PhilHealth employee, Maria Elirene Dizon-Zarate and was able to collect a total of P 1.17 million for her chemotherapy treatment for breast cancer as well as those of her parents is a case in 2010 - 2014 .  Cases has been filed before the Ombudsman and the courts against the involved PhilHealth employee who is no longer connected with the Corporation and who has a warrant of arrest against her.  PhilHealth Regional Office I filed several cases against del Rosario, Zarate and an employee of the Nazareth General Hospital in the Prosecutor's Office in Dagupan City in June 2015.  Zarate was charged with falsification by a public officer while her cohorts were charged with falsification by private individuals, used of falsified documents, swindling and estafa.</p>
        
		<h5><strong>‘Fake Receipts'</strong></h5>
		<p>In relation to Overseas Filipino Workers (OFWs)  remittances, ‘fake receipts' issued to OFWs  hired by at least seventeen (17) recruitment agencies was detected in 2015.</p>
		<p>It was uncovered that out of 1,015 OFWs billed about 533 were issued fake receipts, amounting to P1,279,200.00.  Through its collection efforts, As of May 2019, PhilHealth has collected P208,800 from some of the recruitment agencies, with the remaining balance either a) awaiting settlement, b) with final demand letter, and c) already endorsed to Legal Service of the PhilHealth NCR. Complaints have been filed against these recruitment agencies in the NBI.</p>
		<p>PhilHealth asserts that actions were taken to resolve the issue on the fake receipts. On November 2015, then PhilHealth President and CEO Alexander Padilla wrote NBI Director Atty. Virgilio Mendez requesting for investigation on the reported cases of falsified PORs.  To further augment public awareness on fake receipts, PhilHealth issued advisories and press release warning the public on the proliferation of fake PORs issued to PhilHealth members particularly to OFW.</p>
        
		<h5><strong>Reforms in its fight against fraud</strong></h5>
		<p>PhilHealth has instituted reforms to combat these modus operandi of its providers in cheating the Corporation of the money of its members. Several innovations have been introduced in its IT system through the years. A clean up facility was installed so as to automatically identify double entries of members. Direct filing of claims is no longer accepted except for such conditions as peritoneal dialysis, animal bite, hospitalization abroad, to name a few.</p>
		<p>Adoption of the Machine Learning Identification, Detection and Analysis System (MIDAS) and the Health Insurance Data Analytics Committee (HIDAC) that analyzes voluminous claims data to detect over utilization, among others. Through this method, fraud cases in relation to the overutilization of certain medical conditions such as cataract, pneumonia high risk, sepsis and, recently, diabetic ketoacidosis and pulmonary embolism were investigated and found out to suspiciously high, highest being in Region 11 (Davao Region) and Region 12 (Socsargen Region) or Region 10 (Cagayan) all in Mindanao area. Analysis of data showed that in pulmonary embolism claims, number one hospital in terms of amount of claims was in a Level 1 hospital in the Cagayan Region.</p>
		<p>As of May 31, 2019, 11 health care providers and 22 health care professionals were penalized by the Arbitration Office of PhilHealth due to cataract-related cases involving around P7.8 million worth of fines. Almost 4,000 cases are still on-going to date for cataract-related cases alone.</p>
		<p>E-Claims or the automated submission of claims was implemented in 2018. This ensured that no entry of data would be done in PhilHealth Regional Offices.</p>
		<p>Other mechanisms to deter fraud were instituted such as the use of Claims Form 4 (CF4) for all admissions starting March 01 of this year. CF4 requires more information to better evaluate the truthfulness and quality of service given to its members,</p>
		<p>Other measures include the data-driven transformation of PhilHealth through the continuing implementation; strengthening of Business Intelligence Office; and strengthening operations for efficient and effective delivery and review of roles, performance and assignment. </p>

		<h5><strong>Robust Finances</strong></h5>
		<p>PhilHealth strongly maintains that the fund entrusted to us by our members is secured. In 2018, a net income of P11.6 Billion was realized.   In March this year, a net income of around P 2.44 Billion was recorded with a total fund balance of P127 billion to date.</p>
        
		<h5><strong>Call to Action</strong></h5>
		<p>PhilHealth called on the public to support the fight against health insurance fraud. PhilHealth cautioned its members against institutions or practitioners who use their names to claim for admissions that never happened.  It also encouraged its members to immediately report to the nearest PhilHealth office any incidence of medical procedures undertaken without the members' informed and written consent. It issued the call to keep unethical doctors and abusive facilities from manipulating and exploiting PhilHealth and its members. It also enlisted the support of its media partners in being vigilant about potentially fraudulent practices, emphasizing that every amount saved from fraud and abuses can be used to improve the benefit packages to make these beneficial for more PhilHealth members.  </p>
		<p><em>"I ask our members to maintain your trust in PhilHealth and not to believe in biased reports. PhilHealth is keeping true and steadfast to its mission of Members' First. Hence, our efforts will not stop here. We will continue to initiate reforms that will ensure the integrity of the National Insurance Program, and the viability of the health insurance fund to enable us to fulfill our obligation to our 104 million strong membership,"</em> said PhilHealth OIC, President and CEO Ruben John Basa. (END)</p>

        


