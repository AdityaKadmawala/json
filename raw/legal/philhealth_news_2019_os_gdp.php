		<p>Good afternoon to all of you. We have called this press conference to present our stand against fraudulent claims filed with the Philippine Health Insurance Corporation (PhilHealth). We thank you for coming on such short notice and we assure you that clarifications are in order with utmost regard to truth and honesty.</p>
		<p>Phil Health has been handing out social health benefits to Filipinos for over 24 years. Its coverage spans from select outpatient procedures to treatment of simple to life threatening medical disorders. The Corporation offers its beneficiaries financial access to quality health care. However, PhilHealth's compassion is not reciprocated by some of its partners. Instead some chose to milk the National Health Insurance Program (NHIP) of millions in funds.</p>
		<p>Today, allegations of spurious dialysis claims came out in a major newspaper. A certain dialysis center in Novaliches (Quezon City) is said to have been defrauding PhilHealth by filing claims on behalf of their dead patients as far back as 2016. The Corporation does not condone such acts as it undermines the people's entitlement to one of their basic rights as human beings – the right to appropriate medical care.</p>
		<p>In relation to this case, the Corporation has filed 28 counts of administrative cases for claims for non-admitted/treated patients; misrepresentation by furnishing false or incorrect information; and breach of warranties of accreditation/performance commitment against the mentioned dialysis center. Also we have filed several counts of offenses against doctors for possible involvement between November and December 2018.</p>
		<p>Through its communication campaigns, PhilHealth strongly encourages the participation of its members against fraudulent practices of its institutional and professional health care providers, and even employers. </p>
        
		<p>The Corporation commends the whistleblowers for heeding the call of their conscience and stopping the deceptive scheme of the said dialysis clinic. PhilHealth is pleased that its members are now more empowered to join the battle to help protect the program and its funds.</p>
		<p>The current PhilHealth administration will not back down in its crusade to suppress fraud. Its partnerships with the National Bureau of Investigation, Professional Regulation Commission, Philippine Hospital Association, and Philippine Medical Association are pivotal to this grand undertaking. Under its present leadership, PhilHealth will not let thievery, in any form, prosper.</p>
		<p>The Corporation is instituting reforms to fast-track the resolution of these cases. Our Board of Directors has approved the hiring of additional human resource to ensure speedy identification and resolution of cases. Reforms in the quasi-judicial functions are also given careful deliberation to solidify the impending improvements.</p>
		<p>Recently, the requirement of Claim Form 4 (CF4) for all admissions starting March 1, 2019 did not only facilitate claims evaluation but also promoted accuracy and reinforced validation to ensure quality services given to our members, and deter fraud.</p>
		<p>In addition, the HCI Portal serves as a capable complement to the CF4. It determines a patient's eligibility to PhilHealth benefits or the requirements needed should one be deemed as ineligible to receive social health insurance coverage.</p>
        
		<p>The automation of claims processing through the Electronic Claims brought the national average turn-around-time to only 17 days. This efficiency helps PhilHealth in maintaining consistent service delivery while bringing delight to its health partners by way of timely reimbursements.</p>
		<p>PhilHealth cannot possibly keep its anti-fraud efforts going if it fails to instill discipline among its ranks. Efforts are currently being intensified to cleanse its ranks against officials and employees who are out to destroy PhilHealth's reputation and gains because of their resistance to reforms and reassignments which are long overdue.  </p>
		<p>	The Corporation sees the need to sustain a clean slate if others are to treat its anti-fraud campaign seriously. Moreover, keeping an honest workforce would elevate performance standards while garnering trust of the publics that PhilHealth serves, especially now that the enforcement of the Universal Health Care Act is right around the corner.</p>
		<p>All of us must take on the mantle of accountability and responsibility in protecting the NHIP. We must confront the detractors that are poised to destroy the gains of PhilHealth. The program exists for the sick Filipinos needing appropriate medical attention. We should do everything in our power to keep it out of harm's way.</p>

        


