        <h4>PhilHealth Management Neutralizes Fraud Syndicate<span> January 3, 
          2012</span></h4>
        <p>JUST over two months under new management, the Philippine Health Insurance 
          Corporation (PhilHealth) bared that it has uncovered and neutralized 
          a syndicate that ripped-off a private firm's multimillion-peso premium 
          payment.</p>
        <p><em>"We've already called in the National Bureau of Investigation and 
          the Anti-Money Laundering Council to complete the investigation toward 
          filing the appropriate criminal charges against the culprits,"</em> 
          said Dr. Eduardo P. Banzon, who was designated PhilHealth President 
          and Chief Executive Officer only last Oct. 17.</p>
        <p>Banzon said the premium diversion scam was exposed when PhilHealth 
          staff performing heightened verification and reconciliation of remittances 
          detected a discrepancy in premium collection data.</p>
        <p><em>"A premium payment check was encashed at a private commercial bank. 
          The money was not credited to PhilHealth's account and was diverted 
          elsewhere,"</em> Banzon said.</p>
        <p>It may be recalled that a few years ago, there was a similar tax diversion 
          scheme that was uncovered with the Bureau of Internal Revenue. In the 
          tax diversion scam, syndicate members, including BIR staff and employees 
          of private companies who colluded with the erring bank officers, are 
          now facing trial for money laundering, fraud and falsification.</p>
        <p><em>"There are crooks everywhere. We are warning them. We will spare 
          no effort in running after them. They will be caught, and they will 
          be put behind bars,"</em> Banzon said. <em>"We have zero tolerance for 
          fraud, consistent with President Aquino's 'daang matuwid'' policy."</em></p>
        <p>In response, Banzon created an investigation panel last December 7, 
          2011 and has further designated a senior executive as chief anti-fraudsurveillance 
          officer who will report directly to him and the Board.</p>
        <p>From the investigation, it now appears that a syndicate has been operating 
          as early as 2009. Initial findings indicate that over a hundred million 
          pesos in premium payments were encashed in a private commercial bank. 
          <em>"These premiums never reached PhilHealth,"</em> Banzon said. <em>"We 
          will run after the offenders and take all steps to ensure that these 
          money meant for the health insurance dues of our members are properly 
          remitted and credited to their account,"</em> he added.</p>
        <p><em>"We've also reinforced security controls to protect the integrity 
          of our database,"</em> Banzon said. Administrative charges are now being 
          readied while the filing of the necessary criminal charges is being 
          coordinated with the NBI.</p>
        <p>Meanwhile, Banzon urged all companies <em>"to observe existing (remittance)policies 
          and procedures as prescribed by PhilHealth, and to immediately report 
          any attempts to circumvent protocols to their nearest (PhilHealth)Service 
          Office."</em> (END)</p>
